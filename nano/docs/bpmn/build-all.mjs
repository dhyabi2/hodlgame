// Regenerate holdfun-all.bpmn by merging every numbered model's <bpmn:process>
// and <bpmndi:BPMNDiagram> into one definitions file. IDs are unique per flow
// (each file uses its own prefix), so concatenation is safe.
//
//   node build-all.mjs

import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const files = readdirSync(".")
  .filter((f) => /^\d\d-.*\.bpmn$/.test(f))
  .sort();

const pick = (src, tag) => {
  const re = new RegExp(`<${tag}[\\s\\S]*?</${tag}>`, "g");
  return src.match(re) ?? [];
};

let processes = [];
let diagrams = [];
for (const f of files) {
  const src = readFileSync(f, "utf-8");
  processes.push(`  <!-- ════════ from ${f} ════════ -->`);
  processes.push(...pick(src, "bpmn:process"));
  diagrams.push(...pick(src, "bpmndi:BPMNDiagram"));
}

const out = `<?xml version="1.0" encoding="UTF-8"?>
<bpmn:definitions xmlns:bpmn="http://www.omg.org/spec/BPMN/20100524/MODEL"
  xmlns:bpmndi="http://www.omg.org/spec/BPMN/20100524/DI"
  xmlns:dc="http://www.omg.org/spec/DD/20100524/DC"
  xmlns:di="http://www.omg.org/spec/DD/20100524/DI"
  id="Definitions_holdfun_all"
  targetNamespace="https://holdfun.io/bpmn">

  <!-- GENERATED by build-all.mjs from ${files.join(", ")} — do not edit by hand. -->

${processes.join("\n\n")}

${diagrams.join("\n\n")}

</bpmn:definitions>
`;

writeFileSync("holdfun-all.bpmn", out);
console.log(`merged ${files.length} models into holdfun-all.bpmn (${out.length} bytes)`);
